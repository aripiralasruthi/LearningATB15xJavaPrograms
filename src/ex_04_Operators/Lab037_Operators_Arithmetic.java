package ex_04_Operators;

public class Lab037_Operators_Arithmetic {
    public static void main(String[] args) {
        // Arithmetic operators
        // + (Addition)
        // - (Subtraction)
        // * (Multiplication)
        // / (Division) - Quotient
        // % (Modulus) - Reminder
        //int a,b  = 20; // int a = 0; int b = 20;
        int a = 20;
        //int b = 7;
        float b = 7.0f;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        float d = a/b;
        System.out.println(d);
        System.out.println(a%b);
    }
}
